# 修正：一层内墙按**图纸实测覆盖区间**重做
#
# 对照数据（一层，墙线覆盖区间，实测）：
#   x= 2250  中庭西壁  [(100,250), (2000,6500), (7750,8150)]  → 贯通，两个门洞
#   x= 6050  中庭东壁  [(100,200), (1736,6000)]               → **只到 1736 / 6000**
#   y= 2250  中庭南壁  [(0,250), (1650,6250), (8000,8150)]    → 只到 x 6250
#   y= 6100  中庭北壁  [(100,700), (1700,6200), (8050,8150)]  → 只到 x 6200
#
# 我原来把东壁建成 y 100..8150（贯通）、南壁建到 x 8150、北壁建到 x 8150
# —— **多做了 4400 + 1900 + 1950 mm 的墙**。
# 后果：旋转楼梯（中心 7058,1125、半径 900）被东壁和南壁围成一个死角，
# 用户说的"旋转楼梯两边也没开口"就是这个。
load 'E:/deepseek工作区/sketchup-bridge/build_from_plan.rb'

m = Sketchup.active_model
ents = m.entities
T, H1 = 100.0, 2700.0
SILVER = m.materials['DSH_Silver'] || m.materials.add('DSH_Silver')
SILVER.color = Sketchup::Color.new(176, 180, 186)

def box(x0, y0, x1, y1, z0, h, name)
  g = DshBuild.box_on_ground(Sketchup.active_model.entities, x0, y0, x1, y1, h, name, z0)
  g.material = SILVER
  g
end

# 删掉所有中庭墙（准备按实测重做）
old = ents.grep(Sketchup::Group).select { |g| g.name.to_s.include?('中庭') && g.name.to_s.start_with?('W-') }
old.each(&:erase!)
puts "  已删旧中庭墙 #{old.size} 个"

# ── 中庭西壁：贯通南北，两个门洞（y 250..2000、6500..7750）
box(2200, 100,  2300, 250,  0, H1, 'W-中庭西壁-01')
box(2200, 250,  2300, 2000, 2100, H1 - 2100, 'W-中庭西壁-门楣1')
box(2200, 2000, 2300, 6500, 0, H1, 'W-中庭西壁-02')
box(2200, 6500, 2300, 7750, 2100, H1 - 2100, 'W-中庭西壁-门楣2')
box(2200, 7750, 2300, 8150, 0, H1, 'W-中庭西壁-03')

# ── 中庭东壁：**只从 y=100 到 1736**（图纸实测；北段没有这道墙，
#     所以楼梯那一侧是敞开的）
box(6000, 100, 6100, 1736, 0, H1, 'W-中庭东壁')

# ── 中庭南壁：西端 100..250 一小段 + 门洞 + 主体到 x=6250
box(100, 2200, 250, 2300, 0, H1, 'W-中庭南壁-01')
box(250, 2200, 1650, 2300, 2100, H1 - 2100, 'W-中庭南壁-门楣1')
box(1650, 2200, 6250, 2300, 0, H1, 'W-中庭南壁-02')

# ── 中庭北壁：西段 100..700 + 门洞 + 主体到 x=6200
box(100, 6000, 700, 6100, 0, H1, 'W-中庭北壁-01')
box(700, 6000, 1700, 6100, 2100, H1 - 2100, 'W-中庭北壁-门楣1')
box(1700, 6000, 6200, 6100, 0, H1, 'W-中庭北壁-02')

puts "  已按实测重建中庭四壁"
# 核对：楼梯四周是否敞开
sc = [7058.0, 1125.0]
puts "  楼梯中心 #{sc[0].round},#{sc[1].round}：东壁止于 y=1736、南壁止于 x=6250 → 楼梯南侧与东侧敞开"
puts "  顶层组 #{ents.grep(Sketchup::Group).size} 个"
